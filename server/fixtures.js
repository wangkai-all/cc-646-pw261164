/** 供“载入样本”与测试共用的扁平记录描述。 */
export function scenarioRecords(scenario, asOf = scenario.asOf) {
  const out = [];
  for (const step of scenario.steps) {
    for (const op of step.ops) {
      if (op.op === 'rental' || op.op === 'maintenance') {
        out.push({ ...op, asOf: step.asOf ?? asOf });
      }
    }
  }
  return out;
}

